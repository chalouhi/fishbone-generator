#!/usr/bin/env node
// Writes demo/samples.js and demo/fonts.js from samples/ and fonts/, so the
// demo page loads everything with the page and asks no server for anything
// afterwards (requirement 21). Run after changing a sample or a font:
//   node tools/build-demo-data.js
// The tests check that both files are up to date.
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');

const SAMPLES = [
  ['1-smallest.json', '1 · Smallest file', 'Three steps, one in each stage.'],
  ['2-comprehensive.json', '2 · Comprehensive', 'Three phases, deep children, links, side items.'],
  ['3-long-line.json', '3 · Long line', '28 steps that wrap; every box has a link.'],
  ['4-custom-colours.json', '4 · Custom colours', 'An extra stage and a recoloured one.'],
  ['5-broken.json', '5 · Broken file', 'Seven mistakes, all listed.'],
];

function samplesJS() {
  const list = SAMPLES.map(([file, label, why]) => ({ file, label, why, text: fs.readFileSync(path.join(ROOT, 'samples', file), 'utf8') }));
  return '// Generated by tools/build-demo-data.js from samples/. Do not edit.\n' +
    'window.FISHBONE_SAMPLES = ' + JSON.stringify(list, null, 1) + ';\n';
}
function fontsJS() {
  const b64 = f => fs.readFileSync(path.join(ROOT, 'fonts', f)).toString('base64');
  return '// Generated by tools/build-demo-data.js from fonts/ (Carlito, SIL Open Font Licence 1.1). Do not edit.\n' +
    `window.FISHBONE_FONTS = {regular: "${b64('Carlito-Regular.ttf')}",\nbold: "${b64('Carlito-Bold.ttf')}"};\n`;
}

if (require.main === module) {
  fs.mkdirSync(path.join(ROOT, 'demo'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, 'demo', 'samples.js'), samplesJS());
  fs.writeFileSync(path.join(ROOT, 'demo', 'fonts.js'), fontsJS());
  console.log('wrote demo/samples.js and demo/fonts.js');
}
module.exports = { samplesJS, fontsJS };
